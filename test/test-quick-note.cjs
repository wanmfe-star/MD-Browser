const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { setTimeout: delay } = require('node:timers/promises');
const { app, BrowserWindow } = require('electron');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'md-quick-test-'));
app.setPath('userData',root);
fs.writeFileSync(path.join(root,'quick-note.json'),JSON.stringify({
  id:require('node:crypto').randomUUID(), bounds:{x:80,y:80,width:100,height:80}
}));
app.disableHardwareAcceleration();
if (process.env.MD_TEST_SCALE) app.commandLine.appendSwitch('force-device-scale-factor',process.env.MD_TEST_SCALE);
process.argv.push('--quick-note');
require('../electron/main');
async function until(check) {
  for (let i=0;i<200;i++) { if (await check()) return; await delay(100); }
  throw new Error('Timed out: '+check);
}
(async () => {
  await app.whenReady();
  let win;
  await until(() => (win=BrowserWindow.getAllWindows()[0]) && win.isVisible());
  assert.equal(BrowserWindow.getAllWindows().length,1);
  assert.equal(win.getTitle(),'快捷便签');
  assert.equal(win.isAlwaysOnTop(),false);
  assert.ok(win.getBounds().width >= 360 && win.getBounds().height >= 300,'previously saved tiny notes must recover to the minimum size');
  win.setSize(100,80);
  await until(() => win.getBounds().width >= 360 && win.getBounds().height >= 300);
  const run = code => win.webContents.executeJavaScript(code);
  await until(() => run("document.querySelector('#lock').getAttribute('aria-pressed')==='true'"));
  assert.equal(await run("document.querySelector('#close-note')"),null);
  assert.equal(await run("getComputedStyle(document.querySelector('#quickHandle')).webkitAppRegion"),'no-drag');
  assert.equal(await run("document.querySelector('header').getBoundingClientRect().top"),14);
  assert.equal(win.isMovable(),false);
  await run("document.querySelector('#lock').click()");
  await until(() => win.isMovable());
  await until(() => run("getComputedStyle(document.querySelector('#quickHandle')).webkitAppRegion==='drag'"));
  const [x,y] = win.getPosition();
  win.setPosition(x-25,y+16);
  await until(() => JSON.parse(fs.readFileSync(path.join(root,'quick-note.json'))).bounds?.x === win.getBounds().x);
  await until(() => run("!document.querySelector('#lock').disabled"));
  await run("document.querySelector('#lock').click()");
  await until(() => !win.isMovable());
  await run("document.querySelector('#pin').click()");
  await until(() => win.isAlwaysOnTop());
  await until(() => run("!document.querySelector('#pin').disabled && document.querySelector('#pin').getAttribute('aria-pressed')==='true'"));
  assert.equal(win.isMovable(),false);
  await run("document.querySelector('#pin').click()");
  await until(() => !win.isAlwaysOnTop());
  await until(() => run("!document.querySelector('#pin').disabled && document.querySelector('#pin').getAttribute('aria-pressed')==='false'"));
  const point = await run("(() => {const r=document.querySelector('#body').getBoundingClientRect(); return {x:Math.round(r.x+12),y:Math.round(r.y+12)};})()");
  win.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,...point});
  win.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,...point});
  await until(() => run("document.hasFocus() && document.activeElement.id==='body'"));
  for (const keyCode of '桌面记录') win.webContents.sendInputEvent({type:'char',keyCode});
  await until(() => run("document.querySelector('#body').value==='桌面记录'"));
  const stableBounds = win.getBounds();
  await delay(1200);
  assert.equal(await run("document.hasFocus()"), true, 'native parent changes must not schedule another blur/dock; bounds '+JSON.stringify(win.getBounds()));
  assert.deepEqual(win.getBounds(), stableBounds, 'editing must not move the note');
  await until(() => run("document.querySelector('#local').textContent==='本地已保存'"));
  const originalId = JSON.parse(fs.readFileSync(path.join(root,'quick-note.json'))).id;
  const windowCount = BrowserWindow.getAllWindows().length;
  await run("document.getElementById('new-note').click()");
  await until(() => run("!document.querySelector('#new-note').disabled && document.querySelector('#body').value===''"));
  assert.equal(BrowserWindow.getAllWindows().length,windowCount,'desktop new must reuse the current window');
  assert.match(fs.readFileSync(path.join(root,'便签',originalId+'.md'),'utf8'),/桌面记录/);
  assert.notEqual(JSON.parse(fs.readFileSync(path.join(root,'quick-note.json'))).id,originalId);
  assert.deepEqual(win.getBounds(),stableBounds);
  assert.equal(win.isMovable(),false,'starting a new note must preserve the position lock');
  await run("document.querySelector('#wall').click()");
  let setupMain;
  await until(() => (setupMain=BrowserWindow.getAllWindows().find(w=>w!==win)) && !setupMain.webContents.isLoading());
  await setupMain.webContents.executeJavaScript("window.mdAPI.notesOpen()");
  let extra;
  await until(() => (extra=BrowserWindow.getAllWindows().find(w=>w!==win && w!==setupMain)) && !extra.webContents.isLoading());
  setupMain.close();
  await until(() => setupMain.isDestroyed());
  await until(() => extra.webContents.executeJavaScript("!!document.querySelector('#body') && !document.querySelector('#body').disabled"));
  await delay(1200);
  assert.equal(extra.isFocused(),true,'new note must retain focus after desktop placement finishes');
  const cycleBounds = win.getBounds();
  const cycleContent = await run("({width:innerWidth,height:innerHeight})");
  let slowestActivation = 0;
  for (let cycle = 0; cycle < 20; cycle++) {
    const started = performance.now();
    await run("window.note.edit()");
    await until(() => win.isFocused());
    slowestActivation = Math.max(slowestActivation,performance.now()-started);
    assert.deepEqual(await run("({width:innerWidth,height:innerHeight})"),cycleContent,'focusing must not add a native titlebar or alter the writing area');
    extra.focus();
    await delay(400);
    assert.deepEqual(win.getBounds(),cycleBounds,'activation cycle must preserve the entire window rectangle');
    assert.deepEqual(await run("({width:innerWidth,height:innerHeight})"),cycleContent,'activation cycle must preserve the writing area');
  }
  assert.ok(slowestActivation < 500,'warm window activation must complete within 500ms, got '+slowestActivation);
  console.log('20 focus cycles preserved bounds/content; slowest activation '+Math.round(slowestActivation)+'ms at scale '+(process.env.MD_TEST_SCALE || 'system'));
  await extra.webContents.insertText('临时创意');
  await until(() => extra.webContents.executeJavaScript("document.querySelector('#local').textContent==='本地已保存'"));
  await run("document.querySelector('#wall').click()");
  let main;
  await until(() => (main=BrowserWindow.getAllWindows().find(w => w!==win && w!==extra)) && !main.webContents.isLoading());
  await until(() => main.webContents.executeJavaScript("!document.querySelector('#noteWall').hidden && document.querySelector('#noteCards').textContent.includes('桌面记录')"));
  assert.ok(await main.webContents.executeJavaScript("document.querySelector('#noteNavigation').nextElementSibling.id==='openAI'"));
  assert.equal(await main.webContents.executeJavaScript("document.activeElement.id"),'noteWallTitle');
  await delay(1200);
  assert.equal(main.isFocused(),true,'opening the wall must not return focus to the quick note');
  const { dialog } = require('electron');
  const deleteCard = "Array.from(document.querySelectorAll('.sticky-card')).find(c=>c.textContent.includes('临时创意')).dispatchEvent(new MouseEvent('contextmenu',{bubbles:true}));document.querySelector('#noteContext button').click()";
  let prompts = 0;
  dialog.showMessageBox = async () => ({ response:prompts++ === 0 ? 0 : 1 });
  await main.webContents.executeJavaScript(deleteCard);
  await until(() => prompts===1);
  assert.ok(!extra.isDestroyed());
  await main.webContents.executeJavaScript(deleteCard);
  await until(() => extra.isDestroyed() && main.webContents.executeJavaScript("document.querySelectorAll('.sticky-card').length===1"));
  const trash = path.join(root,'便签','回收站');
  assert.match(fs.readFileSync(path.join(trash,fs.readdirSync(trash)[0]),'utf8'),/临时创意/);
  await main.webContents.executeJavaScript("document.querySelector('.sticky-card').click()");
  let detail;
  await until(() => (detail=BrowserWindow.getAllWindows().find(w=>w.getTitle()==='便签详情')) && !detail.webContents.isLoading());
  assert.equal(await detail.webContents.executeJavaScript("document.querySelector('#detailBody').textContent"),'桌面记录');
  assert.equal(await run("document.querySelector('#body').value"),'');
  await detail.webContents.executeJavaScript("document.querySelector('#editDetail').click()");
  let oldEditor;
  await until(() => (oldEditor=BrowserWindow.getAllWindows().find(w=>w!==win && w!==main && w!==detail)) && !oldEditor.webContents.isLoading());
  const fullText = Array.from({length:40},(_,i)=>'第'+(i+1)+'行完整内容').join('\n');
  await oldEditor.webContents.executeJavaScript("document.querySelector('#body').value="+JSON.stringify(fullText)+";document.querySelector('#body').dispatchEvent(new Event('input'))");
  await until(async () => await detail.webContents.executeJavaScript("document.querySelector('#detailBody').textContent") === fullText);
  oldEditor.close();
  await until(() => oldEditor.isDestroyed());
  detail.close();
  assert.equal(main.isMinimized(),false,'opening details should keep the wall available');
  await run("document.querySelector('#wall').click()");
  await until(() => main.isFocused());
  await main.webContents.executeJavaScript("window.dispatchEvent(new KeyboardEvent('keydown',{key:'f',ctrlKey:true}));");
  assert.equal(await main.webContents.executeJavaScript("document.activeElement.id"),'noteQuery');
  await main.webContents.executeJavaScript("document.querySelector('#showDocs').click();document.querySelector('#showNotes').click()");
  assert.equal(await main.webContents.executeJavaScript("document.activeElement.id"),'noteWallTitle');
  main.close();
  await until(() => main.isDestroyed());
  assert.ok(!win.isDestroyed());
  win.webContents.sendInputEvent({type:'mouseDown',button:'left',clickCount:1,...point});
  win.webContents.sendInputEvent({type:'mouseUp',button:'left',clickCount:1,...point});
  await until(() => run("document.hasFocus() && document.activeElement.id==='body'"));
  win.webContents.sendInputEvent({type:'char',keyCode:'续'});
  await until(() => run("document.querySelector('#body').value.includes('续')"));
  await run("window.note.edit()");
  const keeper = new BrowserWindow({show:false});
  const { Menu } = require('electron');
  const buildMenu = Menu.buildFromTemplate;
  let menuItems, menuCallback;
  Menu.buildFromTemplate = items => ({ popup(options) { menuItems=items; menuCallback=options.callback; } });
  let prevented = false;
  win.emit('system-context-menu',{preventDefault(){prevented=true;}});
  await until(() => !!menuItems);
  assert.equal(prevented,true);
  assert.ok(menuItems.some(item=>item.label==='关闭便签'));
  menuCallback();
  await delay(20);
  menuItems = null;
  await run("document.querySelector('#body').value='右键关闭前的内容';document.querySelector('#body').dispatchEvent(new Event('input'))");
  win.webContents.emit('context-menu',{}, {isEditable:true,editFlags:{canPaste:true,canSelectAll:true}});
  await until(() => !!menuItems);
  assert.ok(menuItems.some(item=>item.role==='paste' && item.enabled));
  menuItems.find(item=>item.label==='关闭便签').click();
  await until(() => win.isDestroyed());
  menuCallback();
  Menu.buildFromTemplate = buildMenu;
  const quickId = JSON.parse(fs.readFileSync(path.join(root,'quick-note.json'))).id;
  assert.match(fs.readFileSync(path.join(root,'便签',quickId+'.md'),'utf8'),/右键关闭前的内容/);
  keeper.destroy();
  console.log('QUICK_NOTE_OK: widget-only launch, desktop placement, pin/unpin, shared note, lower navigation and independent lifetime');
  app.exit(0);
})().catch(error => { console.error(error); app.exit(1); });
