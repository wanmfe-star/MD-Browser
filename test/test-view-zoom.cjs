'use strict';
const {app,BrowserWindow,ipcMain}=require('electron');
const path=require('node:path'),os=require('node:os');
app.setPath('userData',path.join(os.tmpdir(),'view-zoom-'+process.pid));
ipcMain.handle('app:load-connection',()=>({ok:true,data:null}));
ipcMain.handle('media:release',()=>({ok:true}));
const timeout=setTimeout(()=>app.exit(1),30000);
app.whenReady().then(async()=>{
 const win=new BrowserWindow({show:false,width:1360,height:860,webPreferences:{preload:path.join(__dirname,'../electron/preload.js'),contextIsolation:true,nodeIntegration:false,sandbox:false}});
 await win.loadFile(path.join(__dirname,'../renderer/index.html'));
 await win.webContents.executeJavaScript(`(async()=>{
 const check=(v,m)=>{if(!v)throw Error(m);};
 const near=(a,b)=>Math.abs(a-b)<0.001;
 const wheel=(node,dy,ctrl=true,mode=0)=>{const e=new WheelEvent('wheel',{deltaY:dy,deltaMode:mode,ctrlKey:ctrl,bubbles:true,cancelable:true});node.dispatchEvent(e);return e.defaultPrevented;};
 state.currentFile={name:'a.docx',path:'/a.docx',kind:'docx'};applyViewMode();
 wordEditor.load({bytes:[1],model:{blocks:[{id:'a',sourceId:'a',editable:true,text:'Original Word text',format:{align:'left',line:1.5,before:0,after:0,indent:0}}],protectedCount:0}});
 const w=$('wordScroll'),p=$('wordPage'),text=p.textContent;
 check(!wheel(w,100,false),'normal Word scroll not intercepted');
 wheel(w,-10);check(near(Number(p.style.zoom),1.005),'fine Word step');
 wheel(w,-90);check(near(Number(p.style.zoom),1.05),'linear Word delta');
 wheel(w,100);check(near(Number(p.style.zoom),1),'symmetric Word delta');
 wheel(w,100000);check(Number(p.style.zoom)===0.1,'Word minimum');
 wheel(w,-100000);check(Number(p.style.zoom)===4,'Word maximum');
 $('wordZoomReset').click();check(Number(p.style.zoom)===1,'Word reset');
 check(!wordEditor.dirty()&&p.textContent===text,'zoom does not edit Word');
 state.currentFile={name:'a.md',path:'/a.md'};applyViewMode();setEditorFontSize(13);setPreviewFontSize(14);
 wheel(editorPane,-100);check(near(editorFontSize,13.65),'linear editor zoom');
 wheel(previewPane,-100);check(near(previewFontSize,14.7),'linear preview zoom');
 wheel(editorPane,100000);wheel(previewPane,100000);check(editorFontSize===4&&previewFontSize===4,'Markdown lower bounds');
 wheel(editorPane,-100000);wheel(previewPane,-100000);check(editorFontSize===72&&previewFontSize===72,'Markdown upper bounds');
 const c=document.createElement('canvas');c.width=100;c.height=100;
 state.currentFile={name:'a.png',path:'/a.png',kind:'image'};applyViewMode();
 mediaViewer.load(state.currentFile,{kind:'image',url:c.toDataURL()},[state.currentFile]);
 await new Promise(resolve=>$('mediaImage').addEventListener('load',resolve,{once:true}));
 const area=$('imageScroll'),width=()=>parseFloat($('mediaImage').style.width),original=width();
 wheel(area,-10);check(near(width()/original,1.005),'fine image step');
 wheel(area,-90);check(near(width()/original,1.05),'linear image step');
 wheel(area,100000);check(near(width()/original,0.05),'image minimum');
 wheel(area,-100000);check(near(width()/original,8),'image maximum');
 $('imageFit').click();check(near(width(),original),'image reset');
 })()`);
 console.log('View zoom passed: Word linear zoom/reset without document mutation, Markdown decimal sizes/bounds, image linear zoom/bounds/reset');
 clearTimeout(timeout);app.exit(0);
}).catch(e=>{console.error(e);clearTimeout(timeout);app.exit(1);});
